const rating = (source: string, s: Src): Rating => ({ source, url: s.url, value: s.value, scale: 5, count: s.count, period: PERIOD, kind: "карты" });
const review = (source: string, url: string, [author, date, tone, text, lang]: R): VenueReview => ({ source, url, author, ...(date ? { date } : {}), text, tone, ...(lang ? { lang } : {}) });

const sources = (t: Top): [string, Src][] => [["2ГИС", t.g2src], ...(t.ya ? ([["Яндекс Карты", t.ya]] as [string, Src][]) : [])];

const guest = (source: string, s: Src): GuestSource => ({
  source,
  url: s.url,
  period: PERIOD,
  rating: `${String(s.value).replace(".", ",")} из 5 · ${s.count}`,
  positives: s.reviews.filter((r) => r[2] === "+").slice(0, 3).map((r) => r[3]),
  negatives: s.reviews.filter((r) => r[2] === "-").slice(0, 2).map((r) => r[3]),
});

