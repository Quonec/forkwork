from docx import Document
from docx.shared import Pt, Cm, RGBColor
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

OCHRE = RGBColor(0x9F, 0x65, 0x1E)
INK = RGBColor(0x24, 0x1C, 0x10)
MUTED = RGBColor(0x6D, 0x5E, 0x45)
WARN = RGBColor(0xB3, 0x45, 0x2C)


def new_doc():
    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = "Calibri"; st.font.size = Pt(10.5); st.font.color.rgb = INK
    st.element.rPr.rFonts.set(qn("w:eastAsia"), "Calibri")
    for s in doc.sections:
        s.top_margin = Cm(1.8); s.bottom_margin = Cm(1.8)
        s.left_margin = Cm(2.0); s.right_margin = Cm(2.0)
    return doc


def make_helpers(doc):
    def h1(text):
        p = doc.add_paragraph(); r = p.add_run(text)
        r.font.size = Pt(17); r.font.bold = True; r.font.color.rgb = OCHRE

    def h2(text):
        p = doc.add_paragraph(); r = p.add_run(text)
        r.font.size = Pt(13.5); r.font.bold = True; r.font.color.rgb = INK
        p.paragraph_format.space_before = Pt(14); p.paragraph_format.space_after = Pt(4)

    def h3(text):
        p = doc.add_paragraph(); r = p.add_run(text)
        r.font.size = Pt(11.5); r.font.bold = True; r.font.color.rgb = OCHRE
        p.paragraph_format.space_before = Pt(8)

    def para(text, size=10.5, color=None, bold=False, italic=False):
        p = doc.add_paragraph(); r = p.add_run(text)
        r.font.size = Pt(size); r.font.bold = bold; r.font.italic = italic
        if color: r.font.color.rgb = color

    def script(text):
        p = doc.add_paragraph(); p.paragraph_format.left_indent = Cm(0.6)
        r = p.add_run(text); r.font.size = Pt(10); r.font.italic = True; r.font.color.rgb = MUTED

    def bullets(items):
        for it in items:
            p = doc.add_paragraph(style="List Bullet")
            if isinstance(it, tuple):
                r = p.add_run(it[0] + " "); r.bold = True
                p.add_run(it[1])
            else:
                p.add_run(it)

    def shade(cell, hexcolor):
        tcPr = cell._tc.get_or_add_tcPr()
        shd = OxmlElement("w:shd"); shd.set(qn("w:val"), "clear"); shd.set(qn("w:fill"), hexcolor)
        tcPr.append(shd)

    def table(headers, rows, widths=None):
        t = doc.add_table(rows=1, cols=len(headers))
        t.style = "Table Grid"; t.alignment = WD_TABLE_ALIGNMENT.CENTER
        for j, htext in enumerate(headers):
            c = t.rows[0].cells[j]; c.text = ""
            r = c.paragraphs[0].add_run(htext)
            r.font.bold = True; r.font.size = Pt(9.5); r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
            shade(c, "C9822F")
        for row in rows:
            cells = t.add_row().cells
            for j, val in enumerate(row):
                cells[j].text = ""
                r = cells[j].paragraphs[0].add_run(str(val)); r.font.size = Pt(9.5)
        if widths:
            for j, w in enumerate(widths):
                for rw in t.rows:
                    rw.cells[j].width = Cm(w)
        return t

    return h1, h2, h3, para, script, bullets, table


